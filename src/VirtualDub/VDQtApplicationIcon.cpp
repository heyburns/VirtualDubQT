QIcon vdqtApplicationIcon() {
    static const QIcon icon = [] {
        const QByteArray iconData =
            QByteArray::fromBase64(QByteArray(kVirtualDub2IconBase64));
        QBuffer buffer;
        buffer.setData(iconData);
        if (!buffer.open(QIODevice::ReadOnly)) return QIcon();

        QImageReader reader(&buffer, "ico");
        QIcon result;
        const int imageCount = reader.imageCount();
        for (int index = 0; index < imageCount; ++index) {
            if (!reader.jumpToImage(index)) continue;
            const QImage image = reader.read();
            if (!image.isNull()) result.addPixmap(QPixmap::fromImage(image));
        }

        // Preserve a usable icon if an older Qt ICO handler cannot enumerate
        // every embedded resolution.
        if (result.isNull()) {
            buffer.seek(0);
            QImage image;
            if (image.load(&buffer, "ico"))
                result.addPixmap(QPixmap::fromImage(image));
        }
        return result;
    }();
    return icon;
}
